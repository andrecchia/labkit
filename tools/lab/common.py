"""Paths, errors and small helpers shared by every module."""
from __future__ import annotations

import difflib
import os
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
INFRA_DIR = ROOT / "infra"
ANSIBLE_DIR = ROOT / "ansible"
LIBRARY_ROLES = ANSIBLE_DIR / "roles"
TEMPLATES_DIR = ROOT / "templates"
ENVS_DIR = Path(os.environ.get("LAB_ENVS_DIR", ROOT / "envs"))
CACHE_DIR = Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "labkit"
DATA_DIR = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local" / "share")) / "labkit"
VENV_BIN = Path(sys.executable).parent


class LabError(Exception):
    """An error shown to the user without a traceback."""


def log(msg: str) -> None:
    print(f"\033[1;34m==>\033[0m {msg}", file=sys.stderr)


def warn(msg: str) -> None:
    print(f"\033[1;33mwarning:\033[0m {msg}", file=sys.stderr)


def run(cmd: list, check: bool = True, **kw) -> subprocess.CompletedProcess:
    cmd = [str(c) for c in cmd]
    try:
        return subprocess.run(cmd, check=check, **kw)
    except FileNotFoundError:
        raise LabError(f"command not found: {cmd[0]}")
    except subprocess.CalledProcessError as e:
        detail = f"\n{e.stderr.strip()}" if isinstance(e.stderr, str) and e.stderr.strip() else ""
        raise LabError(f"`{' '.join(cmd[:3])} ...` failed (exit {e.returncode}){detail}")


def need(*tools: str) -> None:
    missing = [t for t in tools if not shutil.which(t)]
    if missing:
        raise LabError(f"missing tools on this machine: {', '.join(missing)}")


def suggest(word: str, options) -> str:
    close = difflib.get_close_matches(word, list(options), n=1)
    return f" (did you mean '{close[0]}'?)" if close else ""


def load_yaml(path: Path, default=None):
    if not path.exists():
        return default
    with path.open() as f:
        data = yaml.safe_load(f)
    return default if data is None else data


